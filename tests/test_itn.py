def keys(s: str) -> list[str]:
    toks = T.merge_numbers([dict(w=w) for w in s.split() if T.key(w) or T.is_percent(w)])
    return [t.get("k") or T.key(t["w"]) for t in toks if t.get("k") or T.key(t["w"])]


class Pairs(unittest.TestCase):
    def test_written(self):
        for said, written in PAIRS:
            with self.subTest(said):
                self.assertEqual(itn.text(said), written)

    def test_idempotent(self):
        for said, written in PAIRS:
            with self.subTest(said):
                self.assertEqual(itn.text(written), written)

    def test_key_kept(self):
        """The written form votes and compares like the words said (gold.norm, ensemble._tokens)."""
        for said, written in PAIRS:
            with self.subTest(said):
                self.assertEqual(keys(written), keys(said))

    def test_enough(self):
        self.assertGreaterEqual(len(PAIRS), 150)


class Keys(unittest.TestCase):
    def test_digits_never_multiply(self):
        self.assertEqual(keys("тридцать две 32500"), ["#32", "#32500"])
        self.assertEqual(keys("двадцать 1000"), ["#20", "#1000"])
        self.assertEqual(keys("две тысячи двадцать пять"), ["#2025"])
        self.assertEqual(keys("2 тысячи"), ["#2000"])

    def test_exact_keys(self):
        self.assertNotEqual(keys("1234567"), keys("1234568"))
        self.assertEqual(keys("миллион двести тридцать четыре тысячи пятьсот шестьдесят семь"), ["#1234567"])
        self.assertEqual(keys("2,5"), ["#2.5"])

    def test_percent_is_one_word(self):
        self.assertEqual(keys("19%"), ["#19", "%"])
        self.assertEqual(keys("девятнадцать процентов"), ["#19", "%"])
        self.assertEqual(keys("19% процентов"), ["#19", "%"])
        self.assertEqual(keys("19 %"), ["#19", "%"])

    def test_new_forms(self):
        for w, v in (("тремястами", 300), ("двумястами", 200), ("четырьмястами", 400), ("пятьюстами", 500),
                     ("полтора", 1.5), ("полторы", 1.5), ("миллиард", 10 ** 9), ("четырьмя", 4)):
            with self.subTest(w):
                self.assertEqual(T.number_value(w), v)
        self.assertEqual(keys("полторы тысячи"), ["#1500"])
        self.assertEqual(keys("три миллиарда"), ["#3000000000"])

    def test_pairs(self):
        self.assertEqual(keys("в семь тридцать"), ["в", "#7:30"])
        self.assertEqual(keys("в 7:30"), ["в", "#7:30"])
        self.assertEqual(keys("пять-шесть"), ["#5–6"])
        self.assertEqual(keys("5-6"), ["#5–6"])
        self.assertEqual(keys("за двадцать пять двадцать шесть год"), ["за", "#25", "#26", "год"])
        self.assertEqual(keys("телефон ноль один семь"), ["телефон", "#017"])
        self.assertEqual(keys("ноль один семь"), ["#0", "#1", "#7"])


class Words(unittest.TestCase):
    def test_one_word_with_times(self):
        ws = [dict(w="за", s=0.0, e=0.2, p=0.9), dict(w="двадцать", s=0.2, e=0.5, p=0.8),
              dict(w="пять", s=0.5, e=0.7, p=0.4, _agree=0.5), dict(w="тысяч", s=0.7, e=1.0, p=0.9),
              dict(w="евро.", s=1.0, e=1.3, p=1.0)]
        out = itn.words(ws)
        self.assertEqual([w["w"] for w in out], ["за", "25000", "евро."])
        n = out[1]
        self.assertEqual((n["s"], n["e"], n["p"], n["_agree"]), (0.2, 1.0, 0.4, 0.5))
        self.assertEqual(n["spoken"], "двадцать пять тысяч")
        self.assertEqual(itn.words(out), out)

    def test_millions_keep_the_word_and_its_time(self):
        ws = [dict(w="шестьдесят", s=0.0, e=0.4, p=1.0), dict(w="пять", s=0.4, e=0.6, p=1.0),
              dict(w="миллионов", s=0.6, e=1.2, p=0.7)]
        out = itn.words(ws)
        self.assertEqual([(w["w"], w["s"], w["e"]) for w in out], [("65", 0.0, 0.6), ("миллионов", 0.6, 1.2)])

    def test_percent_word_joins(self):
        ws = [dict(w="девятнадцать", s=0.0, e=0.5, p=1.0), dict(w="процентов,", s=0.5, e=1.0, p=0.6)]
        out = itn.words(ws)
        self.assertEqual([(w["w"], w["s"], w["e"], w["p"]) for w in out], [("19%,", 0.0, 1.0, 0.6)])

    def test_edited_words_stay(self):
        ws = [dict(w="двадцать", s=0.0, e=0.5, p=1.0, edited=True), dict(w="пять", s=0.5, e=1.0, p=1.0)]
        self.assertEqual([w["w"] for w in itn.words(ws)], ["двадцать", "пять"])

    def test_without_pymorphy(self):
        with mock.patch.dict(T._morph, {"m": None, "tried": True}):
            self.assertEqual(itn.text("с семью детьми"), "с семью детьми")
            self.assertEqual(itn.text("двадцать пять тысяч евро"), "25000 евро")


class Renumber(unittest.TestCase):
    def test_doc(self):
        doc = dict(segments=[
            dict(id="g0", text="за двадцать пятый год", words=[
                dict(w="за", s=0, e=1, p=1), dict(w="двадцать", s=1, e=2, p=1), dict(w="пятый", s=2, e=3, p=1),
                dict(w="год", s=3, e=4, p=1)], alts=[dict(model="gigaam-v3", text="за двадцать пятый год")]),
            dict(id="g1", text="две тысячи евро", edited=True, by="owner",
                 words=[dict(w="две", s=0, e=1), dict(w="тысячи", s=1, e=2), dict(w="евро", s=2, e=3)]),
            dict(id="g2", text="пять процентов"),
        ])
        ch = itn.renumber_doc(doc)
        self.assertEqual([c[0] for c in ch], ["g0", "g2"])
        s0, s1, s2 = doc["segments"]
        self.assertEqual(s0["text"], "за 25-й год")
        self.assertEqual(s0["text"], " ".join(w["w"] for w in s0["words"]))
        self.assertEqual(s0["alts"][0]["text"], "за 25-й год")
        self.assertEqual(s1["text"], "две тысячи евро")  # the owner's text
        self.assertEqual(s2["text"], "5%")
        self.assertEqual(itn.renumber_doc(doc), [])


